  department        TEXT,
  given_by          TEXT,
  role              TEXT,
  status            user_status,
  user_access       TEXT,
  leave_date        TIMESTAMP,
  remark            TEXT,
  leave_end_date    TIMESTAMP,
  employee_id       TEXT,
  last_punch_time   TIMESTAMP,
  last_punch_device TEXT,
  page_access       TEXT,
