-- ============================================================
-- STEP 1: Custom ENUM types
-- ============================================================
CREATE TYPE enable_reminder AS ENUM ('yes', 'no');
CREATE TYPE user_status     AS ENUM ('active', 'inactive', 'on_leave', 'terminated');
CREATE TYPE task_status     AS ENUM ('pending', 'in_progress', 'completed', 'rejected', 'done', 'extend');


-- ============================================================
-- STEP 2: Sequences (used by log tables)
-- ============================================================
CREATE SEQUENCE IF NOT EXISTS log_checklist_id_seq;
CREATE SEQUENCE IF NOT EXISTS log_maintenance_id_seq;


-- ============================================================
-- STEP 3: Core tables (in FK dependency order)
-- ============================================================

CREATE TABLE IF NOT EXISTS public.users (
